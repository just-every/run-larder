test('LARDER-001 items, variants, units and parties; ambiguous conversions are refused', async t => {
  const h = await installation(); t.after(() => h.close())
  const timber = await h.command('item.save', { sku: 'WAL-BLANK', name: 'Walnut blank', kind: 'buy', baseUnit: 'each', conversions: [{ unit: 'Bundle', factor: '10' }] })
  assert.deepEqual(timber.conversions, [{ unit: 'bundle', factor: '10' }])
  await h.command('item.save', { sku: 'X', name: 'X', baseUnit: 'each', conversions: [{ unit: 'box', factor: '12' }, { unit: 'Box', factor: '10' }] }, { error: 'AMBIGUOUS_UNIT' })
  await h.command('item.save', { sku: 'Y', name: 'Y', baseUnit: 'each', conversions: [{ unit: 'each', factor: '2' }] }, { error: 'AMBIGUOUS_UNIT' })
  await h.command('item.save', { sku: 'wal-blank', name: 'Dup', baseUnit: 'each' }, { error: 'DUPLICATE_SKU' })
  const large = await h.command('item.save', { sku: 'BRD-L', name: 'Board', kind: 'make', baseUnit: 'each', template: 'Board', attributes: { Size: 'Large' } })
  await h.command('item.save', { sku: 'BRD-S', name: 'Board', kind: 'make', baseUnit: 'each', template: 'Board', attributes: { Size: 'Small' } })
  await h.command('item.save', { sku: 'BRD-L2', name: 'Board', kind: 'make', baseUnit: 'each', template: 'Board', attributes: { Size: 'Large' } }, { error: 'DUPLICATE_VARIANT' })
  const supplier = await h.command('party.save', { name: 'Tasmanian Timber Co', kind: 'supplier', abn: '51 824 753 556' })
  await h.command('party.save', { name: 'tasmanian timber co', kind: 'customer' }, { error: 'DUPLICATE_PARTY' })
  await h.command('partyItem.save', { partyId: supplier.id, itemId: timber.id, partyCode: 'TT-40', price: '9.5', unit: 'bundle' })
  await h.command('partyItem.save', { partyId: supplier.id, itemId: large.id, partyCode: 'TT-40' }, { error: 'AMBIGUOUS_REFERENCE' })
  // Quantities in an undefined unit, or that would round, are refused.
  const customer = await h.command('party.save', { name: 'Harbour Kitchen Co', kind: 'customer' })
  await h.command('so.quote', { customerId: customer.id, promiseDate: '2026-11-01', lines: [{ itemId: timber.id, quantity: '1', unit: 'crate', unitPrice: '1' }] }, { error: 'UNKNOWN_UNIT' })
  const oil = await h.command('item.save', { sku: 'OIL', name: 'Oil', baseUnit: 'l', conversions: [{ unit: 'ml', factor: '0.001' }] })
  await h.command('so.quote', { customerId: customer.id, promiseDate: '2026-11-01', lines: [{ itemId: oil.id, quantity: '0.0005', unit: 'ml', unitPrice: '1' }] }, { error: 'INEXACT_CONVERSION' })
  // Once used, an item's units are fixed.
  await h.command('so.quote', { customerId: customer.id, promiseDate: '2026-11-01', lines: [{ itemId: timber.id, quantity: '2', unit: 'bundle', unitPrice: '1' }] })
  const s = await h.state()
  assert.equal(s.salesOrders[0].lines[0].quantity, '20')
  const current = s.items.find(i => i.id === timber.id)
  await h.command('item.save', { id: timber.id, version: current.version, sku: 'WAL-BLANK', name: 'Walnut blank', baseUnit: 'piece' }, { error: 'UNIT_FIXED' })
})

