test('LARDER-011 returns, transfers and approved counts; corrections reverse, never edit', async t => {
  const h = await installation(); t.after(() => h.close())
  const w = await workshop(h)
  const worker = await h.person('sam@example.test', 'warehouse')
  const t1 = await worker.run('transfer.create', { itemId: w.board.id, fromLocationId: w.loc.id, toLocationId: w.store.id, quantity: '2', reason: 'To dispatch shelf' })
  await worker.run('transfer.create', { itemId: w.board.id, fromLocationId: w.loc.id, toLocationId: w.store.id, quantity: '3', reason: 'Too many' }, { error: 'INSUFFICIENT_STOCK' })
  const q = await h.command('so.quote', { customerId: w.customer.id, promiseDate: '2026-10-28', lines: [{ itemId: w.board.id, quantity: '2', unitPrice: '89' }] })
  const order = await h.command('so.confirm', { orderId: q.id, version: q.version, reserve: false })
  await h.command('so.reserve', { orderId: order.id, locationId: w.store.id })
  const sh = await worker.run('shipment.pick', { orderId: order.id, lines: [{ lineId: order.lines[0].id, locationId: w.store.id, quantity: '2' }] })
  const packed = await worker.run('shipment.pack', { shipmentId: sh.id, version: sh.version, packages: 1 })
  await worker.run('shipment.ship', { shipmentId: sh.id, version: packed.version, carrier: 'Courier' })
  await worker.run('return.receive', { orderId: order.id, lineId: order.lines[0].id, quantity: '3', locationId: w.store.id, disposition: 'quarantine', reason: 'Too many' }, { error: 'RETURN_EXCEEDS' })
  const back = await worker.run('return.receive', { orderId: order.id, lineId: order.lines[0].id, quantity: '1', locationId: w.store.id, disposition: 'quarantine', reason: 'Cracked in transit' })
  // The transfer cannot be reversed: its stock left on the shipment.
  await worker.run('movement.reverse', { documentKind: 'transfers', documentId: t1.id, reason: 'Wrong shelf' }, { error: 'DEPENDENCY' })
  // A count by one person needs another's approval to adjust.
  const count = await worker.run('count.record', { itemId: w.oil.id, locationId: w.loc.id, counted: '1.75', note: 'Half-used tin' })
  assert.equal(count.variance, '-0.25')
  await worker.run('count.approve', { countId: count.id, version: count.version }, { error: 'FORBIDDEN' })
  await h.command('count.approve', { countId: count.id, version: count.version })
  let s = await h.invariant()
  assert.equal(avail(s, w.oil.id).onHand, '1.75')
  const before = s.movements.length
  // A shipment whose goods partly came back cannot be reversed past its return: that would book them twice.
  const blocked = await h.command('movement.reverse', { documentKind: 'shipments', documentId: sh.id, reason: 'Recorded against the wrong order' }, { error: 'DEPENDENCY' })
  assert.equal(blocked.error.details.blockedBy, back.reference)
  assert.equal((await h.invariant()).movements.length, before)
  await h.command('movement.reverse', { documentKind: 'returns', documentId: back.id, reason: 'Belongs to the wrong order' })
  // Reverse the shipment (recorded in error): stock and the reservation come back; the original stays.
  await h.command('movement.reverse', { documentKind: 'shipments', documentId: sh.id, reason: 'Recorded against the wrong order' })
  s = await h.invariant()
  assert.equal(s.movements.length, before + 2)
  assert.equal(avail(s, w.board.id).onHand, '4')
  assert.ok(s.movements.some(m => m.kind === 'shipment')); assert.ok(s.movements.some(m => m.kind === 'shipment-reversal'))
  assert.equal(s.salesOrders[0].lines[0].shipped, '0')
  assert.equal(s.reservations.reduce((n, r) => n + parse(r.quantity), 0n), parse('2'))
  assert.equal(s.shipments[0].status, 'reversed')
})

