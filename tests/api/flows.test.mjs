test('LARDER-013 exceptions are resolved and the complete archive restores into an empty installation', async t => {
  const h = await installation(); t.after(() => h.close())
  const w = await workshop(h)
  const q = await h.command('so.quote', { customerId: w.customer.id, promiseDate: '2026-10-28', lines: [{ itemId: w.board.id, quantity: '6', unitPrice: '89' }] })
  await h.command('so.confirm', { orderId: q.id, version: q.version })
  const po = await h.command('po.draft', { supplierId: w.supplier.id, expectedDate: '2026-01-05', reason: 'Late on purpose', lines: [{ itemId: w.timber.id, quantity: '5', unitPrice: '9.5' }] })
  await h.command('po.approve', { poId: po.id, version: po.version })
  let s = await h.state()
  assert.deepEqual([...new Set(s.exceptions.map(x => x.kind))].sort(), ['late', 'shortage'])
  const late = s.exceptions.find(x => x.kind === 'late')
  await h.command('exception.resolve', { key: late.key, note: 'Supplier rang: shipping Friday' })
  s = await h.state()
  assert.ok(!s.exceptions.some(x => x.kind === 'late'))
  assert.equal(s.resolutions[0].note, 'Supplier rang: shipping Friday')
  const archive = await (await h.request('/api/larder/archive')).json()
  assert.equal(archive.format, 'larder-archive-v1')
  const fresh = await installation(); t.after(() => fresh.close())
  const tampered = { ...archive, movements: archive.movements.map((m, i) => i === 0 ? { ...m, quantity: '99000000' } : m) }
  const refused = await fresh.request('/api/larder/archive/restore', { method: 'POST', raw: JSON.stringify(tampered) })
  assert.equal((await refused.json()).error.code, 'CHECKSUM')
  const restored = await (await fresh.request('/api/larder/archive/restore', { method: 'POST', raw: JSON.stringify(archive) })).json()
  assert.equal(restored.ok, true, JSON.stringify(restored))
  const after = await fresh.invariant()
  assert.deepEqual(after.positions, s.positions); assert.equal(after.salesOrders[0].reference, 'SO-0001')
  assert.deepEqual(after.reservations.map(r => r.quantity), s.reservations.map(r => r.quantity))
  const opening = after.openings[0]
  assert.equal(await (await fresh.request(`/api/larder/attachments/${opening.evidence.id}`)).text(), 'Bay A count sheet, 1 Oct 2026')
  const again = await (await fresh.request('/api/larder/archive/restore', { method: 'POST', raw: JSON.stringify(archive) })).json()
  assert.equal(again.error.code, 'NOT_EMPTY')
  // The restored installation keeps working.
  const more = await fresh.command('so.quote', { customerId: w.customer.id, promiseDate: '2026-11-28', lines: [{ itemId: w.board.id, quantity: '1', unitPrice: '89' }] })
  assert.equal(more.reference, 'SO-0002')
})
