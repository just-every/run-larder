test('LARDER-005 reservations are atomic: competing orders never consume the same stock', async t => {
  const h = await installation(); t.after(() => h.close())
  const w = await workshop(h)
  const orders = []
  for (let i = 0; i < 6; i++) {
    const q = await h.command('so.quote', { customerId: w.customer.id, promiseDate: '2026-10-28', lines: [{ itemId: w.board.id, quantity: '3', unitPrice: '89' }] })
    orders.push(await h.command('so.confirm', { orderId: q.id, version: q.version, reserve: false }))
  }
  const results = await Promise.all(orders.map(o => h.send('so.reserve', { orderId: o.id })))
  for (const r of results) assert.equal(r.res.status, 200, JSON.stringify(r.body))
  const s = await h.invariant()
  const reserved = s.reservations.filter(r => r.itemId === w.board.id).reduce((n, r) => n + parse(r.quantity), 0n)
  assert.equal(reserved, parse('4'))
  // A retry with the same identity returns the recorded outcome, not a second reservation.
  const again = await h.send('so.reserve', { orderId: orders[0].id }, { commandId: results[0].commandId })
  assert.deepEqual(again.body, results[0].body)
  await h.command('so.reserve', { orderId: orders[1].id, extra: true }, { commandId: results[0].commandId, error: 'IDEMPOTENCY' })
})

