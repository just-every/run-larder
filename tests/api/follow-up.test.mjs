import test from 'node:test'
import assert from 'node:assert/strict'
import { installation, evidence } from './harness.mjs'
const day = n => new Date(Date.now() + n * 86400000).toISOString().slice(0, 10)

test('AUTO-001 and LARDER-013 owned cases survive restart and close only after accepted material, completed work, shipment and exact ledger reconciliation', async t => {
  const h = await installation(); t.after(() => h.close())
  const manager = await h.person('manager@example.test', 'manager'), buyer = await h.person('buyer@example.test', 'buyer'), agent = await h.person('agent@example.test', 'agent'), viewer = await h.person('viewer@example.test', 'viewer')
  const loc = await h.command('location.save', { name: 'Ohio workshop' })
  const material = await h.command('item.save', { sku: 'PLATE', name: 'Steel plate', kind: 'buy', baseUnit: 'each' })
  const product = await h.command('item.save', { sku: 'BRACKET', name: 'Steel bracket', kind: 'make', baseUnit: 'each' })
  const supplier = await h.command('party.save', { name: 'Ohio Steel', kind: 'supplier' }), customer = await h.command('party.save', { name: 'Machine Works', kind: 'customer' })
  await h.command('bom.revise', { itemId: product.id, components: [{ itemId: material.id, quantity: '1' }], routing: [{ name: 'Bend bracket', workCentre: 'Press', minutes: 2 }] })
  const orders = [], works = []
  for (let n = 0; n < 2; n++) {
    const q = await h.command('so.quote', { customerId: customer.id, promiseDate: day(-1), lines: [{ itemId: product.id, quantity: '2', unitPrice: '12' }] })
    orders.push(await h.command('so.confirm', { orderId: q.id, version: q.version }))
    const draft = await h.command('wo.draft', { itemId: product.id, quantity: '2', requiredBy: day(-1), reason: `Supply ${orders[n].reference}` })
    works.push(await h.command('wo.release', { workOrderId: draft.id, version: draft.version }))
  }
  let po = await h.command('po.draft', { supplierId: supplier.id, expectedDate: day(-1), reason: 'Steel for both jobs', lines: [{ itemId: material.id, quantity: '4', unitPrice: '3' }] })
  po = await h.command('po.approve', { poId: po.id, version: po.version })
  let s = await h.state()
  const getCase = key => s.followUpCases.find(x => x.key === key)
  const lateKey = `po-late:${po.id}`, late = getCase(lateKey)
  assert.deepEqual(late.related.filter(x => x.kind === 'salesOrders').map(x => x.id).sort(), orders.map(o => o.id).sort())
  assert.deepEqual(late.related.filter(x => x.kind === 'workOrders').map(x => x.id).sort(), works.map(w => w.id).sort())
  const assignment = { key: lateKey, version: 0, ownerId: buyer.id, dueOn: day(-1), nextAction: 'Call supplier for the accepted steel', escalationOwnerId: manager.id, note: 'Both customer orders depend on this receipt' }
  await agent.run('exception.assign', assignment, { error: 'FORBIDDEN' })
  await viewer.run('exception.assign', assignment, { error: 'FORBIDDEN' })
  await buyer.run('exception.assign', assignment, { error: 'FORBIDDEN' })
  for (const ownerId of [agent.id, viewer.id]) await manager.run('exception.assign', { ...assignment, ownerId }, { error: 'INPUT' })
  await manager.run('exception.assign', { ...assignment, escalationOwnerId: buyer.id }, { error: 'INPUT' })
  const commandId = crypto.randomUUID()
  const assigned = await manager.run('exception.assign', assignment, { commandId })
  assert.deepEqual(await manager.run('exception.assign', assignment, { commandId }), assigned)
  s = await h.state()
  assert.equal(getCase(lateKey).ownerId, buyer.id); assert.equal(getCase(lateKey).escalationDue, true)
  assert.equal(getCase(lateKey).history.filter(e => e.type === 'assigned').length, 1)
  assert.ok(getCase(lateKey).history.some(e => e.type === 'escalated'))
  await buyer.run('exception.followUp', { key: lateKey, version: getCase(lateKey).version, dueOn: day(-1), nextAction: 'Inspect incoming material', note: 'Supplier confirms arrival today', evidence: [evidence('Supplier arrival commitment')] })
  s = await h.state()
  await h.command('role.set', { operatorId: buyer.id, role: 'viewer' })
  await buyer.run('exception.followUp', { key: lateKey, version: getCase(lateKey).version, dueOn: day(1), nextAction: 'Unauthorized action', note: 'No longer a writer' }, { error: 'FORBIDDEN' })
  assert.equal((await h.state(viewer.cookie)).followUpCases.find(x => x.key === lateKey).ownerId, buyer.id)
  assert.deepEqual(await manager.run('exception.assign', assignment, { commandId }), assigned)
  await h.command('role.set', { operatorId: buyer.id, role: 'buyer' })
  const file = getCase(lateKey).history.flatMap(e => e.evidence).at(-1)
  assert.equal(await (await h.request(`/api/larder/attachments/${file.id}`)).text(), 'Supplier arrival commitment')
  assert.match(file.sha256, /^[0-9a-f]{64}$/)
  await agent.run('exception.escalate', { key: lateKey, version: getCase(lateKey).version, note: 'Expedite' }, { error: 'FORBIDDEN' })
  await manager.run('exception.escalate', { key: lateKey, version: getCase(lateKey).version, note: 'Manager reviewing both affected orders', evidence: [evidence('Escalation review')] })
  await manager.run('exception.assign', { ...assignment, version: 1 }, { error: 'STALE' })
  await manager.run('exception.resolve', { key: lateKey, note: 'Following up; not a receipt' })
  s = await h.state(); assert.equal(getCase(lateKey).status, 'following up'); assert.ok(s.exceptions.some(e => e.key === lateKey))
  for (const w of works) await manager.run('exception.assign', { ...assignment, key: `wo-blocked:${w.id}`, version: 0, nextAction: `Complete ${w.reference}` })
  po = s.purchaseOrders.find(p => p.id === po.id)
  await h.command('po.revise', { poId: po.id, version: po.version, expectedDate: day(3), note: 'Supplier changed ETA; no goods accepted' })
  s = await h.state(); assert.equal(getCase(lateKey).status, 'following up')
  const receipt = await h.command('receipt.create', { poId: po.id, supplierReference: 'Steel delivery', lines: [{ lineId: po.lines[0].id, locationId: loc.id, quantity: '4', lot: 'STEEL-1', inspection: 'quarantine' }] })
  const lotId = receipt.lines[0].lotId
  s = await h.state(); assert.equal(getCase(lateKey).status, 'following up')
  await h.command('quarantine.decide', { itemId: material.id, locationId: loc.id, lotId, quantity: '2', decision: 'release', reason: 'First two plates passed inspection' })
  await h.command('wo.reserve', { workOrderId: works[0].id })
  await h.command('wo.issue', { workOrderId: works[0].id, lines: [{ itemId: material.id, locationId: loc.id, lotId, quantity: '2' }] })
  s = await h.state()
  let w = s.workOrders.find(w => w.id === works[0].id)
  await h.command('wo.output', { workOrderId: w.id, version: w.version, locationId: loc.id, quantity: '2' })
  s = await h.state(); w = s.workOrders.find(w => w.id === works[0].id)
  await h.command('wo.close', { workOrderId: w.id, version: w.version })
  await h.command('so.reserve', { orderId: orders[0].id })
  let shipment = await h.command('shipment.pick', { orderId: orders[0].id, lines: [{ lineId: orders[0].lines[0].id, locationId: loc.id, quantity: '2' }] })
  shipment = await h.command('shipment.pack', { shipmentId: shipment.id, version: shipment.version, packages: 1 })
  await h.command('shipment.ship', { shipmentId: shipment.id, version: shipment.version, carrier: 'UPS' })
  let handoff = await h.command('handoff.prepare', {})
  const invoice = handoff.lines.find(l => l.type.includes('Customer shipment'))
  handoff = await h.command('handoff.acknowledge', { handoffId: handoff.id, version: handoff.version, entries: [{ lineId: invoice.id, ledgerId: 'BOOKS-INV-1', amount: '1' }] })
  s = await h.state()
  const invoiceKey = `handoff:${handoff.id}:${invoice.id}`
  await manager.run('exception.assign', { ...assignment, key: invoiceKey, version: 0, nextAction: 'Reconcile the issued invoice amount' })
  await manager.run('exception.resolve', { key: invoiceKey, note: 'Bookkeeper checking; amounts still differ' })
  await h.restart()
  s = await h.invariant()
  assert.equal(getCase(lateKey).status, 'following up'); assert.equal(getCase(lateKey).ownerId, buyer.id)
  assert.equal(getCase(`wo-blocked:${works[0].id}`).status, 'closed'); assert.equal(getCase(`wo-blocked:${works[1].id}`).status, 'following up')
  assert.equal(getCase(invoiceKey).status, 'following up'); assert.ok(getCase(lateKey).history.some(e => e.note === 'Supplier confirms arrival today'))
  assert.equal(s.exceptions.some(e => e.key === `promise:${orders[0].id}`), false); assert.ok(s.exceptions.some(e => e.key === `promise:${orders[1].id}`))
  assert.deepEqual(await manager.run('exception.assign', assignment, { commandId }), assigned)
  handoff = await h.command('handoff.acknowledge', { handoffId: handoff.id, version: handoff.version, entries: [{ lineId: invoice.id, ledgerId: 'BOOKS-INV-1', amount: invoice.amountCents }] })
  s = await h.state(); assert.equal(getCase(invoiceKey).status, 'closed'); assert.ok(s.exceptions.some(e => e.kind === 'handoff'))
  await h.command('quarantine.decide', { itemId: material.id, locationId: loc.id, lotId, quantity: '2', decision: 'release', reason: 'Remaining plates passed inspection' })
  s = await h.state(); assert.equal(getCase(lateKey).status, 'closed'); assert.equal(getCase(lateKey).escalationDue, false)
  assert.equal(getCase(`wo-blocked:${works[1].id}`).status, 'following up')
  await h.command('wo.reserve', { workOrderId: works[1].id })
  await h.command('wo.issue', { workOrderId: works[1].id, lines: [{ itemId: material.id, locationId: loc.id, lotId, quantity: '2' }] })
  s = await h.state(); w = s.workOrders.find(w => w.id === works[1].id)
  w = await h.command('wo.output', { workOrderId: w.id, version: w.version, locationId: loc.id, quantity: '2' })
  await h.command('wo.close', { workOrderId: w.id, version: w.version })
  await h.command('so.reserve', { orderId: orders[1].id })
  let secondShipment = await h.command('shipment.pick', { orderId: orders[1].id, lines: [{ lineId: orders[1].lines[0].id, locationId: loc.id, quantity: '2' }] })
  secondShipment = await h.command('shipment.pack', { shipmentId: secondShipment.id, version: secondShipment.version, packages: 1 })
  await h.command('shipment.ship', { shipmentId: secondShipment.id, version: secondShipment.version, carrier: 'UPS' })
  const lastHandoff = await h.command('handoff.prepare', {})
  for (let batch of [handoff, lastHandoff]) await h.command('handoff.acknowledge', { handoffId: batch.id, version: batch.version, entries: batch.lines.map(l => ({ lineId: l.id, ledgerId: `BOOKS-${l.id}`, amount: l.amountCents })) })
  s = await h.invariant()
  assert.equal(getCase(`wo-blocked:${works[1].id}`).status, 'closed')
  assert.ok(!s.exceptions.some(e => ['late', 'shortage', 'blocked', 'promise', 'mismatch', 'handoff', 'quarantine'].includes(e.kind)))

  // Unlotted held goods are fungible: releases consume real inbound chunks in
  // sequence, rather than accidentally crediting every PO for one QC release.
  const pooled = []
  for (const name of ['First pooled delivery', 'Second pooled delivery']) {
    let p = await h.command('po.draft', { supplierId: supplier.id, expectedDate: day(-1), reason: name, lines: [{ itemId: material.id, quantity: '2', unitPrice: '3' }] })
    p = await h.command('po.approve', { poId: p.id, version: p.version })
    await h.command('receipt.create', { poId: p.id, supplierReference: name, lines: [{ lineId: p.lines[0].id, locationId: loc.id, quantity: '2', inspection: 'quarantine' }] })
    await manager.run('exception.assign', { ...assignment, key: `po-late:${p.id}`, version: 0 }); pooled.push(p)
  }
  await h.command('quarantine.decide', { itemId: material.id, locationId: loc.id, quantity: '2', decision: 'release', reason: 'First inbound inspected' })
  s = await h.state()
  assert.equal(getCase(`po-late:${pooled[0].id}`).status, 'closed'); assert.equal(getCase(`po-late:${pooled[1].id}`).status, 'following up')
  await h.command('quarantine.decide', { itemId: material.id, locationId: loc.id, quantity: '2', decision: 'reject', reason: 'Second inbound failed inspection' })
  s = await h.state(); assert.equal(getCase(`po-late:${pooled[1].id}`).status, 'following up'); assert.ok(!s.exceptions.some(e => e.kind === 'quarantine'))

  let expiredPo = await h.command('po.draft', { supplierId: supplier.id, expectedDate: day(-1), reason: 'Expired arrival is not usable acceptance', lines: [{ itemId: material.id, quantity: '1', unitPrice: '3' }] })
  expiredPo = await h.command('po.approve', { poId: expiredPo.id, version: expiredPo.version })
  await manager.run('exception.assign', { ...assignment, key: `po-late:${expiredPo.id}`, version: 0 })
  await h.command('receipt.create', { poId: expiredPo.id, supplierReference: 'Expired arrival', lines: [{ lineId: expiredPo.lines[0].id, locationId: loc.id, quantity: '1', lot: 'EXPIRED-ARRIVAL', dates: { expiresOn: day(-1) } }] })
  s = await h.state(); assert.equal(getCase(`po-late:${expiredPo.id}`).status, 'following up')
  const archived = await (await h.request('/api/larder/archive')).json()
  const restored = await installation(); t.after(() => restored.close())
  const reply = await (await restored.request('/api/larder/archive/restore', { method: 'POST', body: archived })).json()
  assert.equal(reply.ok, true)
  const restoredState = await restored.invariant(), restoredCase = restoredState.followUpCases.find(x => x.key === lateKey)
  assert.equal(restoredCase.status, 'closed'); assert.equal(restoredCase.ownerId, buyer.id)
  assert.deepEqual(restoredCase.history, getCase(lateKey).history)
  assert.equal(await (await restored.request(`/api/larder/attachments/${file.id}`)).text(), 'Supplier arrival commitment')

})
