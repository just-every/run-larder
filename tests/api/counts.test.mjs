import test from 'node:test'
import assert from 'node:assert/strict'
import { installation, workshop, parse, evidence } from './harness.mjs'

test('STOCK-002 blind busy-bin stocktake rejects stale counts, retains recounts and independently approves exact quantity/value adjustments', async t => {
  const h = await installation(); t.after(() => h.close())
  const w = await workshop(h)
  const counter = await h.person('bea@example.test', 'warehouse')
  const manager = await h.person('marco@example.test', 'manager')
  const receiver = await h.person('ruth@example.test', 'warehouse')
  const today = new Date().toISOString().slice(0, 10)
  // Prepare an old command/download before assignment: blind reads must not
  // leak through replay, source exports or attachments either.
  const oldPayload = { itemId: w.timber.id, locationId: w.loc.id, counted: '6' }
  const old = await h.send('count.record', oldPayload, { as: counter.cookie })
  const opening = (await h.state()).openings[0]
  let session = await manager.run('count.schedule', { locationId: w.loc.id, counterId: counter.id, scheduledOn: today, basis: 'value', minimumValue: '50', recountTolerance: '2' })
  assert.deepEqual(session.lines.map(l => l.itemId), [w.board.id, w.timber.id])
  await manager.run('count.schedule', { locationId: w.loc.id, counterId: manager.id, scheduledOn: today, basis: 'bin' }, { error: 'INPUT' })
  let blind = await h.state(counter.cookie)
  assert.equal(blind.blindCounting, true)
  assert.deepEqual(blind.movements, []); assert.deepEqual(blind.counts, []); assert.deepEqual(blind.positions, [])
  for (const line of blind.countSessions[0].lines) for (const field of ['system', 'unitCost', 'value', 'countId', 'attempts', 'frontier']) assert.equal(field in line, false)
  assert.equal(blind.items.some(i => 'standardCost' in i), false)
  for (const path of ['/api/larder/archive', `/api/larder/attachments/${opening.evidence.id}`, '/api/larder/boms.csv']) assert.equal((await h.request(path, { as: counter.cookie })).status, 403)
  await counter.run('count.record', oldPayload, { commandId: old.commandId, error: 'FORBIDDEN' })
  const line = session.lines.find(l => l.itemId === w.timber.id)
  await receiver.run('count.submit', { sessionId: session.id, version: session.version, lineId: line.id, counted: '5' }, { error: 'FORBIDDEN' })
  const submitted = await counter.run('count.submit', { sessionId: session.id, version: session.version, lineId: line.id, counted: '5', note: 'Physical bin count' })
  assert.equal('variance' in submitted, false)
  const count = (await h.state()).counts.find(c => c.id === submitted.id)
  assert.equal(count.variance, '-1')
  const po = await h.command('po.draft', { supplierId: w.supplier.id, expectedDate: today, reason: 'Busy-bin receipt', lines: [{ itemId: w.timber.id, quantity: '2', unitPrice: '9.5' }] })
  const approved = await h.command('po.approve', { poId: po.id, version: po.version })
  await receiver.run('receipt.create', { poId: po.id, supplierReference: 'PACK-1', lines: [{ lineId: approved.lines[0].id, quantity: '2', locationId: w.loc.id, inspection: 'accept' }] })
  const before = await h.state()
  await manager.run('count.approve', { countId: count.id, version: count.version }, { error: 'STALE_COUNT' })
  assert.equal((await h.state()).movements.length, before.movements.length)
  session = before.countSessions[0]
  await manager.run('count.recount', { sessionId: session.id, version: session.version, lineId: line.id, note: 'Receipt after the first observation' })
  blind = await h.state(counter.cookie)
  const recounted = await counter.run('count.submit', { sessionId: session.id, version: blind.countSessions[0].version, lineId: line.id, counted: '7', serials: ['T1','T2','T3','T4','T5','T6','T7'], note: 'Recount after receipt' })
  let s = await h.state(); const current = s.counts.find(c => c.id === recounted.id)
  assert.equal(current.system, '8'); assert.equal(current.counted, '7'); assert.equal(current.valueVariance, '-9.5')
  const decision = await manager.run('count.approve', { countId: current.id, version: current.version, note: 'Confirmed missing blank' })
  assert.equal(decision.approvedBy, manager.id); assert.equal(decision.createdBy, counter.id)
  assert.ok(decision.countedAt); assert.ok(decision.approvedAt)
  assert.ok(decision.countingBasis); assert.equal(decision.serials.length, 7)
  assert.equal(decision.valueVariance, '-9.5')
  s = await h.invariant()
  assert.equal(s.positions.find(p => p.itemId === w.timber.id).quantity, '7')
  assert.equal(s.counts.find(c => c.id === count.id).status, 'superseded')
  assert.equal(s.countSessions[0].lines.find(l => l.id === line.id).attempts.length, 2)
  const boardLine = session.lines.find(l => l.itemId === w.board.id)
  const boardCount = await counter.run('count.submit', { sessionId: session.id, version: s.countSessions[0].version, lineId: boardLine.id, counted: '4' })
  await manager.run('count.approve', { countId: boardCount.id, version: boardCount.version })
  s = await h.state(counter.cookie); assert.equal(s.blindCounting, undefined)
  assert.equal(s.countSessions[0].status, 'complete')
  const handoff = await h.command('handoff.prepare', {})
  const adjustment = handoff.lines.find(l => l.document === current.reference)
  assert.equal(adjustment.quantity, '-1'); assert.equal(adjustment.amountCents, '-9.50')
  const csv = await (await h.request(`/api/larder/handoffs/${handoff.id}.csv`)).text()
  assert.ok(csv.includes(current.reference)); assert.ok(csv.includes('-9.50'))
  // Risk-targeted zero-tolerance sessions require a second observation before
  // any variance can be approved. A lot/serial basis survives archive/restore.
  session = await manager.run('count.schedule', { locationId: w.loc.id, itemId: w.oil.id, counterId: counter.id, scheduledOn: today, basis: 'risk', risk: 'high', recountTolerance: '0' })
  let result = await counter.run('count.submit', { sessionId: session.id, version: session.version, lineId: session.lines[0].id, counted: '1.5' })
  assert.equal(result.status, 'recount required')
  await manager.run('count.approve', { countId: result.id, version: result.version }, { error: 'RECOUNT_REQUIRED' })
  s = await h.state()
  result = await counter.run('count.submit', { sessionId: session.id, version: s.countSessions.find(x => x.id === session.id).version, lineId: session.lines[0].id, counted: '1.5' })
  await manager.run('count.approve', { countId: result.id, version: result.version })
  await h.command('opening.record', { locationId: w.store.id, countedOn: today, valuationBasis: 'supplier-invoice', countedBy: 'Ruth', evidence: evidence(), lines: [{ itemId: w.timber.id, quantity: '3', unitCost: '9.5', lot: 'LOT-CYCLE' }] })
  session = await manager.run('count.schedule', { locationId: w.store.id, counterId: counter.id, scheduledOn: today, basis: 'bin', recountTolerance: '2' })
  const lot = (await h.state()).lots.find(l => l.code === 'LOT-CYCLE')
  assert.equal(session.lines[0].lotId, lot.id)
  result = await counter.run('count.submit', { sessionId: session.id, version: session.version, lineId: session.lines[0].id, counted: '2', serials: ['LOT-A', 'LOT-B'] })
  await counter.run('count.approve', { countId: result.id, version: result.version }, { error: 'FORBIDDEN' })
  await manager.run('count.approve', { countId: result.id, version: result.version })
  s = await h.invariant()
  assert.equal(s.positions.find(p => p.lotId === lot.id).quantity, '2')
  assert.equal(s.counts.find(c => c.id === result.id).lotId, lot.id)
  assert.equal(s.counts.find(c => c.id === result.id).serials.length, 2)
  const archive = await (await h.request('/api/larder/archive')).json()
  const restored = await installation(); t.after(() => restored.close())
  assert.equal((await restored.request('/api/larder/archive/restore', { method: 'POST', body: archive })).status, 200)
  const rs = await restored.invariant()
  assert.deepEqual(rs.countSessions, (await h.state()).countSessions)
  assert.equal(parse(rs.counts.find(c => c.id === current.id).valueVariance), -9500000n)
})
