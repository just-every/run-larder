import test from 'node:test'
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { installation, workshop, evidence } from './harness.mjs'

const today = () => new Date().toISOString().slice(0, 10)
const approval = () => ({ name: 'Casey Customer', reference: 'Customer amendment email', approvedOn: today(), evidence: evidence('Please amend our order as discussed.') })
const currentOrder = async (h, id) => (await h.state()).salesOrders.find(order => order.id === id)
const change = (order, quantity, schedules, overrides = {}) => ({ orderId: order.id, version: order.version, reason: 'Customer approved revised requirement', customerApproval: approval(),
  billingAddress: 'Accounts, 10 First Street, Dayton OH', shippingAddress: 'Receiving, 20 Second Street, Dayton OH',
  lines: order.lines.map(line => ({ lineId: line.id, itemId: line.itemId, quantity, unitPrice: '99', schedules })), ...overrides })

async function ship(h, order, locationId, quantity) {
  const picked = await h.command('shipment.pick', { orderId: order.id, lines: [{ lineId: order.lines[0].id, locationId, quantity }] })
  const packed = await h.command('shipment.pack', { shipmentId: picked.id, version: picked.version, packages: 1 })
  return h.command('shipment.ship', { shipmentId: packed.id, version: packed.version, carrier: 'Local collection' })
}

test('DEMAND-002 approved amendments split promises, preserve issued terms and production costs, cancel only unconsumed commitments, and reject stale or unsafe changes', async t => {
  const h = await installation(); t.after(() => h.close())
  const w = await workshop(h)
  const sales = await h.person('sam-sales@example.test', 'sales')
  const manager = await h.person('morgan-manager@example.test', 'manager')
  const agent = await h.person('amy-agent@example.test', 'agent')
  const wo = await h.command('wo.draft', { itemId: w.board.id, quantity: '4', requiredBy: '2026-11-20', reason: 'Customer production' })
  let work = await h.command('wo.release', { workOrderId: wo.id, version: wo.version })
  await h.command('wo.issue', { workOrderId: work.id, lines: [{ itemId: w.timber.id, locationId: w.loc.id, quantity: '2' }, { itemId: w.oil.id, locationId: w.loc.id, quantity: '0.1' }] })
  work = (await h.state()).workOrders.find(row => row.id === wo.id)
  await h.command('wo.output', { workOrderId: work.id, version: work.version, locationId: w.loc.id, quantity: '1' })
  const po = await h.command('po.draft', { supplierId: w.supplier.id, expectedDate: '2026-11-12', reason: 'Retain supplier commitment', lines: [{ itemId: w.timber.id, quantity: '4', unitPrice: '9.5' }] })
  await h.command('po.approve', { poId: po.id, version: po.version })
  await h.command('transfer.create', { itemId: w.board.id, fromLocationId: w.loc.id, toLocationId: w.store.id, quantity: '1', reason: 'Stage stock at a second location' })
  let order = await h.command('so.quote', { customerId: w.customer.id, promiseDate: '2026-11-15', billingAddress: 'Original billing', shippingAddress: 'Original receiving', lines: [{ itemId: w.board.id, quantity: '8', unitPrice: '89' }] })
  order = await h.command('so.confirm', { orderId: order.id, version: order.version })
  const shipment = await ship(h, order, w.loc.id, '2')
  order = await currentOrder(h, order.id)
  const before = await h.state()
  const proposed = change(order, '12', [{ quantity: '3', date: '2026-11-18' }, { quantity: '7', date: '2026-12-02' }])
  await agent.run('so.changePreview', proposed, { error: 'FORBIDDEN' })
  const preview = await sales.run('so.changePreview', proposed)
  assert.equal(preview.before.lines[0].activeQuantity, '8')
  assert.equal(preview.after.lines[0].activeQuantity, '12')
  assert.equal(preview.after.promiseDate, '2026-12-02')
  assert.equal(preview.customerApproval.basis, 'locally recorded customer attestation')
  assert.ok(preview.impact.reservations.some(row => row.lineId === order.lines[0].id))
  assert.ok(preview.impact.work.some(row => row.id === wo.id && row.incurredMaterialCost === '20.8' && row.costMovementIds.length > 0))
  assert.ok(preview.impact.procurement.some(row => row.id === po.id && row.outstandingExposure === '38'))
  assert.ok(preview.impact.shipments.some(row => row.id === shipment.id && row.commercialTerms.shippingAddress === 'Original receiving'))
  assert.deepEqual((await h.state()).salesOrders.find(row => row.id === order.id), before.salesOrders.find(row => row.id === order.id))
  await agent.run('so.changeApprove', { previewId: preview.id, version: preview.version }, { error: 'FORBIDDEN' })
  order = await sales.run('so.changeApprove', { previewId: preview.id, version: preview.version }, { commandId: 'demand-002-approved-increase' })
  assert.equal(order.lines[0].id, preview.before.lines[0].id)
  assert.equal(order.lines[0].quantity, '12'); assert.equal(order.lines[0].unitPrice, '99')
  assert.equal(order.changeHistory[0].before.shippingAddress, 'Original receiving')
  assert.equal(order.changeHistory[0].after.shippingAddress, proposed.shippingAddress)
  assert.equal(order.billingAddress, proposed.billingAddress)
  assert.equal(order.changeHistory[0].customerApproval.reference, proposed.customerApproval.reference)
  assert.deepEqual(await sales.run('so.changeApprove', { previewId: preview.id, version: preview.version }, { commandId: 'demand-002-approved-increase' }), order)
  let state = await h.invariant()
  assert.deepEqual(state.shipments.find(row => row.id === shipment.id), shipment)
  assert.deepEqual(state.movements, before.movements)
  assert.deepEqual(state.workOrders, before.workOrders)
  assert.deepEqual(state.purchaseOrders, before.purchaseOrders)
  const pegs = state.shortages.flatMap(row => row.pegs).filter(peg => peg.documentId === order.id)
  assert.ok(pegs.some(peg => peg.date === '2026-12-02'))
  assert.deepEqual(state.orderStatuses.sales.find(row => row.id === order.id).lines[0].schedules, proposed.lines[0].schedules)
  // Restore a real portable archive in the pre-snapshot shape. Reads stay usable;
  // unknown historical prices block financial assertions rather than substitute today's price.
  const legacyArchive = await (await h.request('/api/larder/archive')).json()
  const legacyShipment = legacyArchive.records.shipments.find(row => row.id === shipment.id)
  delete legacyShipment.commercialTerms
  for (const line of legacyShipment.lines) { delete line.unitPrice; delete line.movementIds }
  const stable = value => Array.isArray(value) ? value.map(stable) : value && typeof value === 'object' ? Object.fromEntries(Object.keys(value).sort().map(key => [key, stable(value[key])])) : value
  const { exportedAt, checksum, ledger, ...archiveContent } = legacyArchive
  legacyArchive.checksum = createHash('sha256').update(JSON.stringify(stable(archiveContent))).digest('hex')
  const legacy = await installation(); t.after(() => legacy.close())
  assert.equal((await (await legacy.request('/api/larder/archive/restore', { method: 'POST', body: legacyArchive })).json()).ok, true)
  assert.ok((await legacy.state()).pendingHandoff > 0)
  await legacy.command('handoff.prepare', {}, { error: 'HISTORICAL_TERMS' })
  const legacyOrder = await currentOrder(legacy, order.id)
  const legacyChange = change(legacyOrder, '12', [{ quantity: '10', date: '2026-12-02' }])
  legacyChange.lines[0].unitPrice = '100'
  await legacy.command('so.changePreview', legacyChange, { error: 'HISTORICAL_TERMS' })
  const handoff = await h.command('handoff.prepare', {})
  assert.equal(handoff.lines.find(line => line.type.startsWith('Customer shipment')).amountCents, '178.00')
  const returned = await h.command('return.receive', { orderId: order.id, lineId: order.lines[0].id, quantity: '1', locationId: w.store.id, disposition: 'quarantine', reason: 'One damaged board' })
  assert.equal(returned.sources[0].unitPrice, '89')
  const credits = await h.command('handoff.prepare', {})
  assert.equal(credits.lines.find(line => line.type === 'Customer return').amountCents, '-89.00')
  await h.command('movement.reverse', { documentKind: 'returns', documentId: returned.id, reason: 'Return entered against wrong parcel' })
  const reversedReturn = await h.command('handoff.prepare', {})
  assert.equal(reversedReturn.lines.find(line => line.type === 'Correction (reversal)').amountCents, '89.00')
  order = await currentOrder(h, order.id)
  // A picked commitment at Dispatch shelf must survive release at Workshop.
  const picked = await h.command('shipment.pick', { orderId: order.id, lines: [{ lineId: order.lines[0].id, locationId: w.store.id, quantity: '1' }] })
  await h.command('so.cancelLine', { orderId: order.id, version: order.version, lineId: order.lines[0].id, quantity: '10' }, { error: 'PICKED_COMMITMENT' })
  await sales.run('so.changePreview', change(order, '2', []), { error: 'PICKED_COMMITMENT' })
  await sales.run('so.changePreview', change(order, '1', []), { error: 'SHIPPED_COMMITMENT' })
  // Reduce to one still-open picked unit; history accumulates cancellation rather than rewriting gross ordered quantity.
  const cancellation = await sales.run('so.changePreview', change(order, '3', [{ quantity: '1', date: '2026-12-02' }]))
  order = await manager.run('so.changeApprove', { previewId: cancellation.id, version: cancellation.version })
  assert.equal(order.lines[0].quantity, '12'); assert.equal(order.lines[0].cancelled, '9')
  state = await h.invariant()
  assert.equal(state.reservations.filter(row => row.demandId === order.id).reduce((n, row) => n + Number(row.quantity), 0), 1)
  assert.equal(state.shipments.find(row => row.id === picked.id).status, 'picked')
  assert.equal(state.reservations.find(row => row.demandId === order.id).locationId, w.store.id)
  const packed = await h.command('shipment.pack', { shipmentId: picked.id, version: picked.version, packages: 1 })
  await h.command('shipment.ship', { shipmentId: picked.id, version: packed.version, carrier: 'Local collection' })
  order = await currentOrder(h, order.id)
  assert.equal(order.status, 'shipped'); assert.deepEqual(order.lines[0].schedules, [])
  const stale = await sales.run('so.changePreview', change(order, '4', [{ quantity: '1', date: '2026-12-12' }]))
  await h.command('location.save', { name: 'Intervening business change' })
  await manager.run('so.changeApprove', { previewId: stale.id, version: stale.version }, { error: 'STALE' })
  assert.deepEqual(await currentOrder(h, order.id), order)
  await sales.run('so.changePreview', change(order, '4', [{ quantity: '2', date: '2026-12-12' }]), { error: 'SCHEDULE_QUANTITY' })
  await h.command('movement.reverse', { documentKind: 'shipments', documentId: shipment.id, reason: 'Original parcel never left' })
  const corrections = await h.command('handoff.prepare', {})
  assert.equal(corrections.lines.find(line => line.type === 'Correction (reversal)').amountCents, '-178.00')
  const final = await h.invariant()
  assert.deepEqual(final.workOrders, before.workOrders); assert.deepEqual(final.purchaseOrders, before.purchaseOrders)
})

test('DEMAND-002 dated quantities net once, stale review is refused, and unpick resolves a blocked cancellation without posting stock', async t => {
  const h = await installation(); t.after(() => h.close())
  const w = await workshop(h)
  const material = await h.command('item.save', { sku: 'ORDERED-PANEL', name: 'Ordered panel', kind: 'buy', baseUnit: 'each', salePrice: '12' })
  let order = await h.command('so.quote', { customerId: w.customer.id, promiseDate: '2026-11-01', lines: [{ itemId: material.id, quantity: '4' }] })
  order = await h.command('so.confirm', { orderId: order.id, version: order.version })
  const preview = await h.command('so.changePreview', change(order, '4', [{ quantity: '1.5', date: '2026-11-03' }, { quantity: '2.5', date: '2026-11-17' }]))
  order = await h.command('so.changeApprove', { previewId: preview.id, version: preview.version })
  let state = await h.state()
  const shortage = state.shortages.find(row => row.itemId === material.id)
  assert.equal(shortage.shortage, '4')
  assert.deepEqual(shortage.pegs.map(peg => [peg.date, peg.quantity]), [['2026-11-03', '1.5'], ['2026-11-17', '2.5']])
  await h.command('so.cancelLine', { orderId: order.id, version: order.version, lineId: order.lines[0].id, quantity: '1' }, { error: 'INPUT' })
  const cancelledLine = await h.command('so.cancelLine', { orderId: order.id, version: order.version, lineId: order.lines[0].id, quantity: '1', customerApproval: approval(), reason: 'Customer reduced one panel' })
  assert.equal(cancelledLine.changeHistory.at(-1).customerApproval.reference, approval().reference)
  const boardOrder = await h.command('so.quote', { customerId: w.customer.id, promiseDate: '2026-11-01', lines: [{ itemId: w.board.id, quantity: '2' }] })
  let confirmed = await h.command('so.confirm', { orderId: boardOrder.id, version: boardOrder.version })
  const picked = await h.command('shipment.pick', { orderId: confirmed.id, lines: [{ lineId: confirmed.lines[0].id, locationId: w.loc.id, quantity: '2' }] })
  await h.command('so.changePreview', change(confirmed, '0', []), { error: 'PICKED_COMMITMENT' })
  const before = await h.state()
  await h.command('shipment.unpick', { shipmentId: picked.id, version: picked.version, reason: 'Customer cancelled before dispatch' })
  const cancellation = await h.command('so.changePreview', change(confirmed, '0', []))
  confirmed = await h.command('so.changeApprove', { previewId: cancellation.id, version: cancellation.version })
  assert.equal(confirmed.status, 'cancelled')
  assert.equal(confirmed.lines[0].cancelled, '2')
  state = await h.invariant()
  assert.deepEqual(state.movements, before.movements)
  assert.equal(state.reservations.filter(row => row.demandId === confirmed.id).length, 0)
  assert.equal(state.shipments.find(row => row.id === picked.id).status, 'cancelled')
})
