import { test, expect, type Page } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
import { join } from 'node:path'
const origin = process.env.LARDER_BASE_URL || 'http://127.0.0.1:8787'
async function command(page: Page, type: string, payload: object) {
  const r = await page.request.post(origin + '/api/larder/commands', { headers: { Origin: origin }, data: { commandId: crypto.randomUUID(), type, payload } })
  const b = await r.json(); expect(b.ok, JSON.stringify(b.error)).toBe(true); return b.result
}
async function settled(page: Page) { await expect(page.locator('main')).toHaveAttribute('aria-busy', 'false'); await expect(page.getByRole('alert')).toHaveCount(0) }
async function shots(page: Page, stage: string, region?: ReturnType<Page['locator']>) {
  if (!process.env.LARDER_SCREENSHOTS) return
  await mkdir(process.env.LARDER_SCREENSHOTS, { recursive: true })
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 1000 })
    expect(await page.locator('main').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    if (region) await region.screenshot({ path: join(process.env.LARDER_SCREENSHOTS, `${width}-CAP-009-${stage}.png`) })
    else await page.screenshot({ path: join(process.env.LARDER_SCREENSHOTS, `${width}-CAP-009-${stage}.png`), fullPage: true })
  }
}
const local = (d: Date) => new Date(d.getTime() - d.getTimezoneOffset() * 60000).toISOString().slice(0, 16)
async function planTimes(page: Page, ref: string) {
  await page.setViewportSize({ width: 1440, height: 1000 }); await page.goto(origin + '/app#schedule'); await page.reload(); await settled(page)
  await page.getByRole('group', { name: 'Schedule span' }).getByRole('button', { name: 'Week', exact: true }).click()
  await page.locator('.gantt .bar').filter({ hasText: ref }).first().click()
  return page.locator('.job-panel .operations time').evaluateAll(nodes => nodes.map(n => n.getAttribute('datetime')!))
}

test('CAP-009 schedule maintenance, log breakdown, assign repair/ETA, inspect recovery, evidence-backed release and retained trail at 1440/390', async ({ page }) => {
  if (!process.env.LARDER_OPEN) throw new Error('Private local entry required.')
  await page.goto(process.env.LARDER_OPEN); await page.waitForURL(u => ['/setup', '/app'].includes(u.pathname))
  if (new URL(page.url()).pathname === '/setup') { await page.getByRole('checkbox').check(); await page.getByRole('button', { name: 'Finish setup', exact: true }).click(); await page.waitForURL(u => u.pathname === '/app') }
  const tag = crypto.randomUUID().slice(0, 6), today = new Date().toISOString().slice(0, 10), center = `Router ${tag}`
  const raw = await command(page, 'item.save', { sku: `AL-${tag}`, name: 'Aluminum blank', kind: 'buy', baseUnit: 'each' })
  const item = await command(page, 'item.save', { sku: `BRACKET-${tag}`, name: `Ohio bracket ${tag}`, kind: 'make', baseUnit: 'each' })
  await command(page, 'bom.revise', { itemId: item.id, components: [{ itemId: raw.id, quantity: '1' }], routing: [{ name: 'Machine bracket', workCentre: center, minutes: 45 }, { name: 'Finish bracket', workCentre: `Bench ${tag}`, minutes: 10 }] })
  let work = await command(page, 'wo.draft', { itemId: item.id, quantity: '4', requiredBy: today, reason: 'Customer brackets' }); work = await command(page, 'wo.release', { workOrderId: work.id, version: work.version })
  const dispatchActor = (await (await page.request.get(origin + '/api/larder/state')).json()).actor
  work = await command(page, 'wo.operation.assign', { workOrderId: work.id, version: work.version, sequence: 1, operatorId: dispatchActor.id })
  const next = await command(page, 'wo.draft', { itemId: item.id, quantity: '2', requiredBy: today, reason: 'Following customer order' })
  const before = await planTimes(page, work.reference)
  const card = page.getByRole('heading', { name: 'Equipment maintenance', exact: true }).locator('../..')
  await card.getByText('Record equipment maintenance', { exact: true }).click()
  await card.getByLabel('Maintenance work center', { exact: true }).selectOption(center)
  await card.getByLabel('Maintenance kind', { exact: true }).selectOption('breakdown')
  const eta = new Date(Date.now() + 2 * 86400000)
  await card.getByLabel('Expected equipment return (local time)', { exact: true }).fill(local(eta))
  await card.getByLabel('Repair owner', { exact: true }).fill('Alex at Ohio Machine Repair')
  await card.getByLabel('CMMS record ID', { exact: true }).fill(`CMMS-${tag}`)
  await card.getByLabel('Maintenance reason', { exact: true }).fill('Spindle fault; isolate router pending bearing repair')
  await shots(page, 'create', card)
  await card.getByRole('button', { name: 'Record maintenance', exact: true }).click(); await settled(page)
  const state = await (await page.request.get(origin + '/api/larder/state')).json(), m = state.maintenance.find((m: any) => m.workCentre === center)
  const record = page.getByRole('article', { name: `Maintenance ${m.reference}`, exact: true })
  await expect(record).toContainText(work.reference); await expect(record).toContainText(next.reference); await expect(record).toContainText('release required')
  const after = await planTimes(page, work.reference)
  expect(Date.parse(after[0])).toBeGreaterThan(Date.parse(before[0])); expect(Date.parse(after[0])).toBeGreaterThanOrEqual(Date.parse(new Date(local(eta)).toISOString()))
  expect(Date.parse(after.at(-1)!)).toBeGreaterThan(Date.parse(before.at(-1)!))
  await expect(page.locator('.job-panel')).toContainText('Provisional recovery')
  await shots(page, 'recovery')
  await record.getByText(`Update ${m.reference} repair`, { exact: true }).click()
  await record.getByLabel(`${m.reference} repair owner`, { exact: true }).fill('Alex and Pat')
  await record.getByLabel(`${m.reference} expected return (local time)`, { exact: true }).fill(local(new Date(Date.now() + 3 * 86400000)))
  await record.getByLabel(`${m.reference} update note`, { exact: true }).fill('Replacement bearing and technician booked')
  await shots(page, 'update', record)
  await record.getByRole('button', { name: `Save ${m.reference} repair update`, exact: true }).click(); await settled(page)
  await page.goto(origin + `/app#make/wo/${work.id}`); await settled(page)
  await expect(page.getByRole('region', { name: 'Pinned operation tasks', exact: true })).toContainText('Equipment unavailable')
  await expect(page.getByRole('button', { name: 'Start step 1', exact: true })).toBeDisabled()
  await shots(page, 'blocked-work', page.getByRole('region', { name: 'Pinned operation tasks', exact: true }))
  const denied = await page.request.post(origin + '/api/larder/commands', { headers: { Origin: origin }, data: { commandId: crypto.randomUUID(), type: 'wo.operation.start', payload: { workOrderId: work.id, version: work.version, sequence: 1, workCentre: center } } })
  expect((await denied.json()).error.code).toBe('MAINTENANCE')
  await page.goto(origin + '/app#schedule'); await settled(page)
  await record.getByText(`Release ${m.reference} equipment`, { exact: true }).click()
  await record.getByLabel(`${m.reference} repair and release note`, { exact: true }).fill('Bearing replaced, spindle test run passed')
  await record.getByLabel(`${m.reference} repair evidence file`, { exact: true }).setInputFiles({ name: 'spindle-repair.txt', mimeType: 'text/plain', buffer: Buffer.from('Bearing replaced; runout inspection passed') })
  await shots(page, 'release-prepared', record)
  await record.getByRole('button', { name: `Release ${m.reference}`, exact: true }).click(); await settled(page)
  await expect(record).toContainText('Released'); await expect(record).toContainText('Bearing replaced, spindle test run passed')
  const released = await planTimes(page, work.reference)
  expect(Date.parse(released[0])).toBeLessThan(Date.parse(after[0]))
  await expect(page.locator('.job-panel')).not.toContainText('Provisional recovery')
  await record.getByText(`${m.reference} maintenance trail`, { exact: true }).click()
  await expect(record).toContainText('Spindle fault'); await expect(record).toContainText('Replacement bearing and technician booked')
  await shots(page, 'released-trail', record)
  const file = await record.getByRole('link', { name: 'Repair evidence: spindle-repair.txt', exact: true }).getAttribute('href')
  expect(await (await page.request.get(origin + file)).text()).toBe('Bearing replaced; runout inspection passed')
  // The preventive door retains a future window and moves a whole operation past it.
  await page.setViewportSize({ width: 1440, height: 1000 })
  await card.getByText('Record equipment maintenance', { exact: true }).click()
  await card.getByLabel('Maintenance work center', { exact: true }).selectOption(center)
  await card.getByLabel('Maintenance kind', { exact: true }).selectOption('preventive')
  const future = new Date(Date.now() + 5 * 86400000)
  while ([0, 6].includes(future.getDay())) future.setDate(future.getDate() + 1)
  future.setHours(7, 0, 0, 0)
  const plannedStart = `${future.getFullYear()}-${String(future.getMonth() + 1).padStart(2, '0')}-${String(future.getDate()).padStart(2, '0')}`
  const preventiveWork = await command(page, 'wo.draft', { itemId: item.id, quantity: '1', requiredBy: plannedStart, plannedStart, reason: 'Future preventive-window check' })
  await card.getByLabel('Maintenance start (local time; preventive only)', { exact: true }).fill(local(future))
  await card.getByLabel('Expected equipment return (local time)', { exact: true }).fill(local(new Date(future.getTime() + 3600000)))
  await card.getByLabel('Repair owner', { exact: true }).fill('Pat / preventive service')
  await card.getByLabel('Maintenance reason', { exact: true }).fill('Scheduled lubrication and safety inspection')
  await card.getByRole('button', { name: 'Record maintenance', exact: true }).click(); await settled(page)
  await expect(card).toContainText('Preventive')
  const pmState = await (await page.request.get(origin + '/api/larder/state')).json(), pm = pmState.maintenance.find((r: any) => r.workCentre === center && r.kind === 'preventive')
  const pmRecord = page.getByRole('article', { name: `Maintenance ${pm.reference}`, exact: true })
  await expect(pmRecord).toContainText(preventiveWork.reference)
  const recovery = pmRecord.getByRole('row').filter({ hasText: preventiveWork.reference }).first().locator('time').first()
  expect(Date.parse((await recovery.getAttribute('datetime'))!)).toBeGreaterThanOrEqual(Date.parse(pm.expectedReturnAt))
  await shots(page, 'preventive', card)
  await page.goto(origin + `/app#make/wo/${work.id}`); await settled(page)
  await page.getByLabel('Step 1 station', { exact: true }).fill('Shared fabrication tablet')
  await page.getByLabel('Step 1 start reason', { exact: true }).fill('Assigned job ready after equipment check')
  await page.getByRole('button', { name: 'Start step 1', exact: true }).click(); await settled(page)
  await expect(page.getByRole('region', { name: 'Pinned operation tasks', exact: true })).toContainText('Started by')
  await shots(page, 'available-work', page.getByRole('region', { name: 'Pinned operation tasks', exact: true }))
  const end = await (await page.request.get(origin + '/api/larder/state')).json(), final = end.workOrders.find((w: any) => w.id === work.id)
  expect(final.output).toBe('0'); expect(final.requiredBy).toBe(today); expect(final.operationStates[0].status).toBe('running')
  await page.reload(); await settled(page); await page.goto(origin + '/app#schedule'); await settled(page)
  await expect(record).toContainText('Released'); await expect(record).toContainText(`CMMS-${tag}`)
})
